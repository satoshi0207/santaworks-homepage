/** 記事ページの eyebrow に出す「テーマ ／ 手法」。真実源はこのファイルだけにする */
export function eyebrowOf(slug: string): string {
  const p = posts.find((x) => x.slug === slug);
  if (!p) return "";
  return `${THEMES[p.theme]} / ${KINDS[p.kind]}`;
}
